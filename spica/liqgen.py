"""Generate the Liquidsoap config from stations.json.

One request.queue per station (fed by the picker through a file), one playlist
fallback (the heuristic rotation), a short crossfade, and one MP3 mount. That is
the whole mixer — no jingles, no ducking, no per-track stamping.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

from . import config


def encoder(codec: str) -> str:
    """The Liquidsoap encoder for one codec.

    FLAC goes out as Ogg FLAC: bare FLAC over Icecast gives players no framing to
    resync on, and every client that matters reads Ogg.
    """
    if codec == "opus":
        bitrate = config.CODEC_BITRATE["opus"]
        return f"%opus(bitrate={bitrate}, samplerate=48000, channels=2)"
    if codec == "flac":
        # 44.1 kHz, the library's own rate: resampling a lossless stream to 48 would
        # make it not-lossless for nothing.
        return "%ogg(%flac(samplerate=44100, channels=2))"
    bitrate = config.CODEC_BITRATE["mp3"]
    return f"%mp3(bitrate={bitrate}, samplerate=48000, stereo=true)"


def outputs_for(st: config.Station, password: str) -> list[str]:
    """One Icecast output per stream: one encoder each, one mount each."""
    lines: list[str] = []
    for codec in st.stream_set:
        lines += [
            f"output.icecast({encoder(codec)},",
            f'  id="out_{st.id}_{codec}", start=false,',
            # Icecast only applies ICY titles to mp3; the Ogg mounts carry their own.
            f"  send_icy_metadata={'true' if codec == 'mp3' else 'false'},",
            f'  host="{config.ICECAST_OUTPUT_HOST}", port={config.ICECAST_OUTPUT_PORT}, '
            f'password="{password}", mount="{st.mount_for(codec)}",',
            f'  name="{st.name}", description="{st.description or st.name} · '
            f'{config.CODEC_LABEL[codec]}", s_{st.id})',
            "",
        ]
    return lines


def render(stations: list[config.Station], password: str) -> str:
    out: list[str] = [
        "# Generated by `python -m spica.liqgen` from stations.json — do not edit.",
        "settings.init.allow_root := true",
        "settings.log.level := 3",
        # Control server: the admin UI closes it after a station change and docker
        # restarts the container with the new script. Note the nesting: in 2.4 the
        # port and bind address live under `server.telnet`, not under `server`.
        "settings.server.telnet := true",
        "settings.server.telnet.port := 1234",
        'settings.server.telnet.bind_addr := "0.0.0.0"',
        "",
    ]
    for st in stations:
        out += [
            f"# ---- {st.id}: {st.name} " + "-" * max(0, 40 - len(st.id) - len(st.name)),
            f"q_{st.id} = request.queue(id=\"q_{st.id}\")",
            f"def poll_{st.id}() =",
            f"  if file.exists(\"{st.queue_file}\") then",
            f"    contents = string.trim(file.contents(\"{st.queue_file}\"))",
            f"    file.remove(\"{st.queue_file}\")",
            "    if contents != \"\" then",
            f'      log("[{st.id}] queueing #{{contents}}")',
            f"      ignore(q_{st.id}.push(request.create(contents)))",
            "    end",
            "  end",
            "end",
            f"thread.run(every=1.0, poll_{st.id})",
            f"s_{st.id} = mksafe(fallback(id=\"src_{st.id}\", track_sensitive=true, [",
            f"  q_{st.id},",
            f"  playlist(id=\"pool_{st.id}\", mode=\"normal\", reload_mode=\"watch\", \"{st.pool_file}\")",
            "]))",
            # crossfade() rejects a fallible source and returns a fallible one, so
            # it sits between two mksafe calls (verified on 2.4.6).
            f"s_{st.id} = mksafe(crossfade(duration=3.0, s_{st.id}))",
            # The ledger has to be honest whether or not anybody is listening, so
            # the station is stamped from the source rather than from Icecast: a
            # closed mount has no title. Same "artist - title" shape Icecast would
            # have shown, because that is what plays.note() already parses.
            f"def stamp_{st.id}(m) =",
            '  a = m["artist"]',
            '  t = m["title"]',
            '  if a != "" and t != "" then',
            f'    file.write("{st.now_file}", data=a ^ " - " ^ t ^ "\\n", append=true)',
            "  end",
            "end",
            f"s_{st.id}.on_metadata(synchronous=true, stamp_{st.id})",
            # A silent sink keeps the clock alive with no listeners: decoding only,
            # about 1% of a core per station, instead of the ~12% the encoder costs.
            f"output.dummy(id=\"clock_{st.id}\", fallible=true, s_{st.id})",
        ]
        out += outputs_for(st, password)
    return "\n".join(out)


def main() -> int:
    stations = config.load_stations()
    password = os.environ.get("ICECAST_SOURCE_PASSWORD", "hackme")
    target = Path(os.environ.get("SPICA_LIQ", str(config.CONFIG_DIR / "spica.liq")))
    target.write_text(render(stations, password), encoding="utf-8")
    print(f"wrote {target} with {len(stations)} station(s): {', '.join(s.id for s in stations)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
